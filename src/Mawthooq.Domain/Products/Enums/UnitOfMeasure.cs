        SachetLiquid = 24, // كيس جل / غسول فم مفرد

        // ==========================================
        // 3. Medical Supplies & Consumer Goods (المستلزمات والحفاضات: 41+)
        // ==========================================
        OuterBox = 41,     // كرتونة كبرى / علبة خارجية ضخمة
        Piece = 42,        // قطعة (وحدة عامة للأجهزة، فرش الأسنان، إلخ)
        Pair = 43,         // زوج (للقفازات الطبية أو الجوارب الضاغطة)
        Diaper = 44,       // حفاضة / حبة مفردة من كرتونة الحفاضات
        Roll = 45          // بكرة (شاش، بلاستر طبي، قطن رول)
    }
}
