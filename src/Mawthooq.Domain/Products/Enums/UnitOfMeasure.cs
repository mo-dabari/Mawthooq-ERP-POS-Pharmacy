namespace Mawthooq.Domain.Products.Enums
{
    public enum UnitOfMeasure
    {
        // ==========================================
        // 1. Pharmaceutical Units (الأدوية التقليدية: 1 - 20)
        // ==========================================
        Disc = 1,        // قرص / حبة
        Capsule = 2,       // كبسولة
        Strip = 3,         // شريط
        Box = 4,           // علبة / باكت
        Ampoule = 5,       // أمبول (حقنة سائلة)
        Vial = 6,          // فيل (حقنة بودرة مجهزة للحل)
        Sachet = 7,        // كيس فوار / بودرة
        Suppository = 8,   // قمع / لبوسة

        // ==========================================
        // 2. Liquids & Topicals (السوائل والمواضيعية: 21 - 40)
        // ==========================================
